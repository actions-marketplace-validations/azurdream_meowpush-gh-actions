import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

export async function buildDistribution({ outdir = 'dist' } = {}) {
  const destination = path.resolve(root, outdir);
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/index.js'],
    outfile: path.join(destination, 'index.cjs'),
    bundle: true,
    platform: 'node',
    target: 'node24',
    format: 'cjs',
    minify: true,
    legalComments: 'inline',
    metafile: true,
    banner: {
      js: '// Generated by npm run build. Source: src/. See licenses.txt for dependency notices.',
    },
  });
  const packages = new Set();
  for (const file of Object.keys(result.metafile.inputs)) {
    const match = file.match(/^(node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (match) packages.add(match[1]);
  }
  const notices = [];
  for (const directory of [...packages].sort()) {
    const pkg = JSON.parse(
      await readFile(path.join(root, directory, 'package.json'), 'utf8'),
    );
    let license;
    for (const name of [
      'LICENSE',
      'LICENSE.md',
      'LICENSE.txt',
      'license',
      'license.md',
    ]) {
      try {
        license = await readFile(path.join(root, directory, name), 'utf8');
        break;
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
    }
    if (!license) throw new Error(`Missing license notice for ${pkg.name}.`);
    notices.push(`${pkg.name}@${pkg.version}\n${license.trim()}\n`);
  }
  await mkdir(destination, { recursive: true });
  await writeFile(
    path.join(destination, 'licenses.txt'),
    notices.join('\n---\n\n'),
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  await buildDistribution();
}
